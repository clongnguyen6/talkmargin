// Menu-bar template glyph: speech bubble with two cut-out lines, 18x18 pt, y down.
// One geometry, three outputs: SVG master, single-page vector PDF, PNG @1x/@2x.
// Usage: swift menu-glyph.swift <out-dir>
// Grid: body x 1-17, y 1-15; lines x 4-14 at y 5-7 and 9-11 (integer edges, crisp at @1x and @2x).
// Nonzero fill: body and tail run one way, the line holes the other way.
import AppKit

enum Cmd { case m(Double, Double), l(Double, Double), c(Double, Double, Double, Double, Double, Double), z }

let k = 0.78     // superellipse-like corners (n ~ 3), matches the app bubble's soft-square shape
let q = 0.5523   // circular quarter arc
func body() -> [Cmd] {
    let (cx, cy, a, b) = (9.0, 8.0, 8.0, 7.0)
    return [.m(cx + a, cy),
            .c(cx + a, cy + k * b, cx + k * a, cy + b, cx, cy + b),
            .c(cx - k * a, cy + b, cx - a, cy + k * b, cx - a, cy),
            .c(cx - a, cy - k * b, cx - k * a, cy - b, cx, cy - b),
            .c(cx + k * a, cy - b, cx + a, cy - k * b, cx + a, cy), .z]
}
// Tail: leaves the body's lower left, rounded tip near (2.2, 17.1), concave back edge to the bottom.
let tail: [Cmd] = [.m(6.4, 12.0),
                   .l(7.4, 14.5),
                   .c(5.9, 15.7, 4.3, 16.7, 2.8, 17.15),
                   .c(2.2, 17.3, 1.75, 16.9, 1.95, 16.4),
                   .c(2.4, 15.4, 2.65, 14.1, 2.7, 12.6), .z]
// Capsule hole, counter-orientation to the body.
func line(_ y: Double) -> [Cmd] {
    let (x0, x1, r) = (4.0, 14.0, 1.0)
    return [.m(x0 + r, y),
            .c(x0 + r - q * r, y, x0, y + r - q * r, x0, y + r),
            .c(x0, y + r + q * r, x0 + r - q * r, y + 2 * r, x0 + r, y + 2 * r),
            .l(x1 - r, y + 2 * r),
            .c(x1 - r + q * r, y + 2 * r, x1, y + r + q * r, x1, y + r),
            .c(x1, y + r - q * r, x1 - r + q * r, y, x1 - r, y), .z]
}
let glyph = body() + tail + line(5) + line(9)

func fmt(_ v: Double) -> String { String(format: "%g", (v * 1000).rounded() / 1000) }
func svgPath() -> String {
    glyph.map { cmd -> String in
        switch cmd {
        case let .m(x, y): return "M\(fmt(x)) \(fmt(y))"
        case let .l(x, y): return "L\(fmt(x)) \(fmt(y))"
        case let .c(a, b, c, d, e, f): return "C\(fmt(a)) \(fmt(b)) \(fmt(c)) \(fmt(d)) \(fmt(e)) \(fmt(f))"
        case .z: return "Z"
        }
    }.joined()
}
// CG path in a y-up context of `size` points: flip y.
func cgPath(size: Double) -> CGPath {
    let p = CGMutablePath(); let s = size / 18
    func pt(_ x: Double, _ y: Double) -> CGPoint { CGPoint(x: x * s, y: (18 - y) * s) }
    for cmd in glyph {
        switch cmd {
        case let .m(x, y): p.move(to: pt(x, y))
        case let .l(x, y): p.addLine(to: pt(x, y))
        case let .c(a, b, c, d, e, f): p.addCurve(to: pt(e, f), control1: pt(a, b), control2: pt(c, d))
        case .z: p.closeSubpath()
        }
    }
    return p
}

let out = URL(fileURLWithPath: CommandLine.arguments[1])
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 18 18">
<!-- TalkMargin menu-bar template glyph. Generated by design/final/src/menu-glyph.swift; edit there. -->
<path fill="#000" fill-rule="nonzero" d="\(svgPath())"/>
</svg>

"""
try! svg.write(to: out.appendingPathComponent("MenuBarIconTemplate.svg"), atomically: true, encoding: .utf8)

var box = CGRect(x: 0, y: 0, width: 18, height: 18)
let pdfURL = out.appendingPathComponent("MenuBarIconTemplate.pdf") as CFURL
let pdf = CGContext(pdfURL, mediaBox: &box, [kCGPDFContextTitle: "TalkMargin menu-bar icon"] as CFDictionary)!
pdf.beginPDFPage(nil)
pdf.addPath(cgPath(size: 18)); pdf.setFillColor(gray: 0, alpha: 1); pdf.fillPath(using: .winding)
pdf.endPDFPage(); pdf.closePDF()

for (scale, name) in [(1, "MenuBarIconTemplate.png"), (2, "MenuBarIconTemplate@2x.png")] {
    let px = 18 * scale
    let ctx = CGContext(data: nil, width: px, height: px, bitsPerComponent: 8, bytesPerRow: 0,
                        space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    ctx.setShouldAntialias(true)
    ctx.addPath(cgPath(size: Double(px))); ctx.setFillColor(gray: 0, alpha: 1); ctx.fillPath(using: .winding)
    let rep = NSBitmapImageRep(cgImage: ctx.makeImage()!)
    rep.size = NSSize(width: 18, height: 18)  // 72 dpi at @1x, 144 dpi at @2x
    try! rep.representation(using: .png, properties: [:])!.write(to: out.appendingPathComponent(name))
}
print("wrote SVG, PDF, PNG @1x/@2x to \(out.path)")
